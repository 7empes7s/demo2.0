//! `d2-door`: demo flow and test-vector tooling for the Door protocol core.

use d2_door::{
    verify, Credential, Disclosure, Holder, IdentityProvider, Issuer, IssuerKey, IssuerSecret,
    MemoryStore, MockIdProvider, UniquenessKey, UniquenessStore,
};
use rand::rngs::OsRng;
use std::collections::BTreeMap;
use std::net::TcpListener;
use std::process::ExitCode;

const USAGE: &str = "usage:
  d2-door demo                    enrol the demo people with the mock identity provider and present
  d2-door vectors --out <path>    write test vectors generated by this code
  d2-door check <path>            check a vectors file against this code (drift test)
  d2-door serve --issuer-key <path> [--issuer-key <path> ...] [--host 127.0.0.1] [--port 8092]
                                  run the verifier HTTP service (POST /presentations/verify)
  d2-door dev-world --out <dir> [--epoch <n>] --person <name>:<adult|minor>:<path> ...
                                  MOCK ONLY: a fresh issuer, its public key and one credential per person
  d2-door present --credential <path> --issuer-key <path> --context <id> --challenge <hex>
                  [--levels <n>] [--adult] [--epoch-disclosed]
                                  holder side: print a presentation as JSON";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let words: Vec<&str> = args.iter().map(String::as_str).collect();
    let result = match words[..] {
        ["demo"] => demo(),
        ["vectors", "--out", path] => vectors(path),
        ["check", path] => check(path),
        ["serve", ref rest @ ..] => flags(rest).and_then(|f| serve(&f)),
        ["dev-world", ref rest @ ..] => flags(rest).and_then(|f| dev_world(&f)),
        ["present", ref rest @ ..] => flags(rest).and_then(|f| present(&f)),
        _ => Err(USAGE.to_string()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("{message}");
            ExitCode::from(2)
        }
    }
}

fn vectors(path: &str) -> Result<(), String> {
    let v = d2_door::vectors::generate()?;
    let text = serde_json::to_string_pretty(&v).map_err(|e| e.to_string())? + "\n";
    std::fs::write(path, text).map_err(|e| format!("{path}: {e}"))?;
    println!("wrote {path}: {} presentations", v.presentations.len());
    Ok(())
}

fn check(path: &str) -> Result<(), String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    let v: d2_door::vectors::Vectors =
        serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))?;
    let n = d2_door::vectors::check(&v)?;
    println!("{path}: {n} checks passed");
    Ok(())
}

fn demo() -> Result<(), String> {
    let provider = MockIdProvider::demo();
    let mut door = Issuer::new(UniquenessKey::generate(&mut OsRng), MemoryStore::new());
    door.add_epoch(IssuerSecret::generate(
        1,
        "2026-01-01T00:00:00Z",
        "2026-12-31T23:59:59Z",
        &mut OsRng,
    ))
    .map_err(|e| e.to_string())?;
    let key = door.issuer_key(1).unwrap().clone();
    println!("issuer key, epoch 1: {}...", &key.bbs_public_key[..32]);

    let esch = Disclosure {
        jurisdiction_levels: 2,
        adult: true,
        epoch: false,
    };
    for token in provider.tokens() {
        let assertion = provider.assert_identity(token).map_err(|e| e.to_string())?;
        let holder = Holder::new(&mut OsRng);
        let commit = holder.commit().map_err(|e| e.to_string())?;
        println!(
            "\n{token}: {} in {}",
            if assertion.adult { "adult" } else { "minor" },
            assertion.jurisdiction_path
        );
        let issuance = match door.enrol(&assertion, 1, &commit.commitment, &mut OsRng) {
            Ok(i) => i,
            Err(e) => {
                println!("  enrolment refused: {e}");
                continue;
            }
        };
        let credential = holder
            .finalize(&key, &issuance, &commit.blind)
            .map_err(|e| e.to_string())?;
        println!(
            "  enrolled; Door now holds {} entries for epoch 1",
            door.store().count(1)
        );
        for context in ["agora:lu.esch", "agora:lu", "booth:round-1"] {
            let challenge = b"demo";
            let p = credential
                .present(&key, context, challenge, &esch)
                .map_err(|e| e.to_string())?;
            let v = verify(&key, &p, context, challenge, &esch).map_err(|e| e.to_string())?;
            println!(
                "  {context:<16} {}  lives in {}  adult={}",
                v.pseudonym,
                v.disclosed.jurisdiction_path.as_deref().unwrap_or("-"),
                v.disclosed.adult.map(|a| a.to_string()).unwrap_or_default()
            );
        }
    }
    Ok(())
}

/// `--name value` pairs (repeatable) and bare switches (`--adult`), in order.
type Flags = BTreeMap<String, Vec<String>>;

const SWITCHES: &[&str] = &["--adult", "--epoch-disclosed"];

fn flags(rest: &[&str]) -> Result<Flags, String> {
    let mut out = Flags::new();
    let mut i = 0;
    while i < rest.len() {
        let name = rest[i];
        if !name.starts_with("--") {
            return Err(format!("unexpected argument {name:?}\n{USAGE}"));
        }
        if SWITCHES.contains(&name) {
            out.entry(name.to_string()).or_default().push(String::new());
            i += 1;
            continue;
        }
        let value = rest
            .get(i + 1)
            .ok_or_else(|| format!("{name} needs a value\n{USAGE}"))?;
        out.entry(name.to_string())
            .or_default()
            .push(value.to_string());
        i += 2;
    }
    Ok(out)
}

fn one<'a>(f: &'a Flags, name: &str) -> Result<&'a str, String> {
    match f.get(name).map(Vec::as_slice) {
        Some([v]) => Ok(v),
        Some(_) => Err(format!("{name} given more than once")),
        None => Err(format!("{name} is required\n{USAGE}")),
    }
}

fn optional<'a>(f: &'a Flags, name: &str, default: &'a str) -> Result<&'a str, String> {
    if f.contains_key(name) {
        one(f, name)
    } else {
        Ok(default)
    }
}

fn check_known(f: &Flags, known: &[&str]) -> Result<(), String> {
    match f.keys().find(|k| !known.contains(&k.as_str())) {
        Some(k) => Err(format!("unknown option {k}\n{USAGE}")),
        None => Ok(()),
    }
}

fn serve(f: &Flags) -> Result<(), String> {
    check_known(f, &["--issuer-key", "--host", "--port"])?;
    let keys = d2_door::http::load_keys(f.get("--issuer-key").map(Vec::as_slice).unwrap_or(&[]))?;
    let host = optional(f, "--host", "127.0.0.1")?;
    let port: u16 = optional(f, "--port", "8092")?
        .parse()
        .map_err(|_| "--port must be a number from 0 to 65535".to_string())?;
    let listener = TcpListener::bind((host, port)).map_err(|e| format!("{host}:{port}: {e}"))?;
    let addr = listener.local_addr().map_err(|e| e.to_string())?;
    let epochs: Vec<String> = keys.keys().map(u32::to_string).collect();
    eprintln!(
        "d2-door verifier on http://{addr} (epochs {})",
        epochs.join(", ")
    );
    d2_door::http::serve(
        listener,
        keys,
        d2_door::http::TIMEOUT,
        d2_door::http::MAX_CONNECTIONS,
    );
    Ok(())
}

fn dev_world(f: &Flags) -> Result<(), String> {
    check_known(f, &["--out", "--epoch", "--person"])?;
    let out = std::path::Path::new(one(f, "--out")?);
    let epoch: u32 = optional(f, "--epoch", "1")?
        .parse()
        .map_err(|_| "--epoch must be a number".to_string())?;
    let people = f
        .get("--person")
        .ok_or(format!("--person is required\n{USAGE}"))?;
    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;

    let mut provider = MockIdProvider::new();
    let mut names = Vec::new();
    for (i, spec) in people.iter().enumerate() {
        let mut parts = spec.splitn(3, ':');
        let (Some(name), Some(age), Some(path)) = (parts.next(), parts.next(), parts.next()) else {
            return Err(format!(
                "--person {spec:?}: expected <name>:<adult|minor>:<path>"
            ));
        };
        if name.is_empty() || !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-') {
            return Err(format!(
                "--person {spec:?}: name must be letters, digits or -"
            ));
        }
        let adult = match age {
            "adult" => true,
            "minor" => false,
            _ => return Err(format!("--person {spec:?}: age must be adult or minor")),
        };
        provider.add(name, &format!("test-person-{:04}", i + 1), adult, path);
        names.push(name);
    }

    let mut door = Issuer::new(UniquenessKey::generate(&mut OsRng), MemoryStore::new());
    door.add_epoch(IssuerSecret::generate(
        epoch,
        "2026-01-01T00:00:00Z",
        "2026-12-31T23:59:59Z",
        &mut OsRng,
    ))
    .map_err(|e| e.to_string())?;
    let key = door.issuer_key(epoch).ok_or("issuer key missing")?.clone();
    write_json(&out.join("issuer-key.json"), &key)?;
    for name in names {
        let assertion = provider.assert_identity(name).map_err(|e| e.to_string())?;
        let holder = Holder::new(&mut OsRng);
        let commit = holder.commit().map_err(|e| e.to_string())?;
        let issuance = door
            .enrol(&assertion, epoch, &commit.commitment, &mut OsRng)
            .map_err(|e| format!("{name}: {e}"))?;
        let credential = holder
            .finalize(&key, &issuance, &commit.blind)
            .map_err(|e| format!("{name}: {e}"))?;
        write_json(&out.join(format!("{name}.credential.json")), &credential)?;
    }
    println!("wrote {} (epoch {epoch})", out.display());
    Ok(())
}

fn present(f: &Flags) -> Result<(), String> {
    check_known(
        f,
        &[
            "--credential",
            "--issuer-key",
            "--context",
            "--challenge",
            "--levels",
            "--adult",
            "--epoch-disclosed",
        ],
    )?;
    let credential: Credential = read_json(one(f, "--credential")?)?;
    let key: IssuerKey = read_json(one(f, "--issuer-key")?)?;
    let challenge =
        hex::decode(one(f, "--challenge")?).map_err(|e| format!("--challenge must be hex: {e}"))?;
    let levels: usize = optional(f, "--levels", "0")?
        .parse()
        .map_err(|_| "--levels must be a number".to_string())?;
    let wants = Disclosure {
        jurisdiction_levels: levels,
        adult: f.contains_key("--adult"),
        epoch: f.contains_key("--epoch-disclosed"),
    };
    let p = credential
        .present(&key, one(f, "--context")?, &challenge, &wants)
        .map_err(|e| e.to_string())?;
    println!("{}", serde_json::to_string(&p).map_err(|e| e.to_string())?);
    Ok(())
}

fn read_json<T: serde::de::DeserializeOwned>(path: &str) -> Result<T, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))
}

fn write_json<T: serde::Serialize>(path: &std::path::Path, value: &T) -> Result<(), String> {
    let text = serde_json::to_string_pretty(value).map_err(|e| e.to_string())? + "\n";
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}
