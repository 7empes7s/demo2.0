//! `d2-booth`: verify a published board, run a demo round, test-vector tooling.

use d2_booth::vectors::{check, generate, Vectors};
use d2_booth::{verify_board, Board};
use std::process::ExitCode;

const USAGE: &str = "usage:
  d2-booth verify <board.json>     replay a published board and print the tally it proves
  d2-booth demo [--out <board.json>]
                                   run a small round in one process (guardians, voters, tally)
  d2-booth vectors --out <path>    write test vectors generated by this code
  d2-booth check <path>            check a vectors file against this code (drift test)";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let words: Vec<&str> = args.iter().map(String::as_str).collect();
    let result = match words[..] {
        ["verify", path] => verify(path),
        ["demo"] => demo(None),
        ["demo", "--out", path] => demo(Some(path)),
        ["vectors", "--out", path] => vectors(path),
        ["check", path] => check_file(path),
        _ => Err(USAGE.to_string()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("{message}");
            ExitCode::from(2)
        }
    }
}

fn verify(path: &str) -> Result<(), String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    let board: Board = d2_booth::board::parse_board(&text)
        .map_err(|e| format!("{path}: invalid ({}): {e}", e.code()))?;
    let tally = verify_board(&board).map_err(|e| format!("{path}: invalid ({}): {e}", e.code()))?;
    let state = d2_booth::replay(&board).map_err(|e| e.to_string())?;
    let params = state.params().ok_or("no params")?;
    println!(
        "round {}: {} entries, chain and every proof verified",
        params.round_id,
        board.entries.len()
    );
    println!(
        "sign-ups {}, counted {}, guardians used {:?}",
        tally.signups, tally.counted, tally.guardians_used
    );
    for (label, count) in params.options.iter().zip(&tally.counts) {
        println!("  {label}: {count}");
    }
    Ok(())
}

fn demo(out: Option<&str>) -> Result<(), String> {
    let script = d2_booth::vectors::Script {
        round_id: "booth:demo".to_string(),
        options: ["yes", "no", "abstain"].map(String::from).to_vec(),
        guardians: 5,
        threshold: 3,
        voters: (0..20)
            .map(|i| (format!("nym-{i:02}"), vec![i % 3]))
            .collect(),
        decrypting_guardians: vec![1, 2, 4],
    };
    let mut seed = [0u8; 32];
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut seed);
    let (board, tally) = d2_booth::vectors::run(&script, seed).map_err(|e| e.to_string())?;
    let checked = verify_board(&board).map_err(|e| e.to_string())?;
    assert_eq!(checked, tally);
    println!(
        "demo round: {} entries, tally {:?}",
        board.entries.len(),
        tally.counts
    );
    if let Some(path) = out {
        let text = serde_json::to_string_pretty(&board).map_err(|e| e.to_string())? + "\n";
        std::fs::write(path, text).map_err(|e| format!("{path}: {e}"))?;
        println!("wrote {path}");
    }
    Ok(())
}

fn vectors(path: &str) -> Result<(), String> {
    let v = generate().map_err(|e| e.to_string())?;
    let text = serde_json::to_string_pretty(&v).map_err(|e| e.to_string())? + "\n";
    std::fs::write(path, text).map_err(|e| format!("{path}: {e}"))?;
    println!(
        "wrote {path}: {} entries, {} must-fail cases",
        v.board.entries.len(),
        v.must_fail.len()
    );
    Ok(())
}

fn check_file(path: &str) -> Result<(), String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    let v: Vectors = serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))?;
    let n = check(&v)?;
    println!("{path}: {n} checks passed");
    Ok(())
}
