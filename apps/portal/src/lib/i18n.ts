export const DICTS: Record<UiLang, Dict> = { en, fr };
export const UI_LANGS: UiLang[] = ["fr", "en"];
export const UI_LANG_LABELS: Record<UiLang, string> = { fr: "Français", en: "English" };

export function translate(lang: UiLang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** The browser's language if it is French or English, else French (the commune's working language). */
export function guessLang(preferred: readonly string[]): UiLang {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "fr" || base === "en") return base;
  }
  return "fr";
}
