export const DICTS: Record<Lang, Dict> = { en, fr, de, lb, pt };

export const LANG_LABELS: Record<Lang, string> = {
  lb: "Lëtzebuergesch",
  fr: "Français",
  de: "Deutsch",
  en: "English",
  pt: "Português",
};

/** BCP 47 tags for date formatting. */
export const LOCALES: Record<Lang, string> = { lb: "lb-LU", fr: "fr-LU", de: "de-LU", en: "en-GB", pt: "pt-PT" };

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** Browsers have no Luxembourgish date data (Intl prints "2026 M10 2"), so lb is written by hand. */
const LB_MONTHS = ["Januar", "Februar", "Mäerz", "Abrëll", "Mee", "Juni", "Juli", "August", "September", "Oktober", "November", "Dezember"];

export function formatDate(lang: Lang, iso: string | null | undefined): string {
  if (!iso) return "";
  const d = new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso);
  if (Number.isNaN(d.getTime())) return iso;
  try {
    if (lang === "lb") {
      const [y, m, day] = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Luxembourg" }).format(d).split("-").map(Number);
      return `${day}. ${LB_MONTHS[m - 1]} ${y}`;
    }
    return new Intl.DateTimeFormat(LOCALES[lang], { day: "numeric", month: "long", year: "numeric", timeZone: "Europe/Luxembourg" }).format(d);
  } catch {
    return iso;
  }
}

/** The browser's preferred language if we speak it, else French (the Chamber's working language). */
/** A date as a calendar tile: the day of the month and the month, short ("7", "Oct"). */
export function shortDay(lang: Lang, iso: string): { day: string; month: string } {
  const d = new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso);
  if (Number.isNaN(d.getTime())) return { day: "", month: "" };
  const [, m, day] = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Luxembourg" }).format(d).split("-").map(Number);
  const month =
    lang === "lb"
      ? LB_MONTHS[m - 1].slice(0, 3)
      : new Intl.DateTimeFormat(LOCALES[lang], { month: "short", timeZone: "Europe/Luxembourg" }).format(d).replace(/\.$/, "");
  return { day: String(day), month };
}

export function guessLang(preferred: readonly string[]): Lang {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "lb" || base === "fr" || base === "de" || base === "en" || base === "pt") return base;
  }
  return "fr";
}
